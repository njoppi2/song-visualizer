/* Usage: SONGVIZ_PLAYWRIGHT_MODULE=/path/to/playwright node experiments/check_listening_examples.cjs URL */
const assert = require('node:assert/strict');
const {chromium} = require(process.env.SONGVIZ_PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const url = process.argv[2];
  assert(url, 'Passe a URL dos exemplos de escuta.');
  const browser = await chromium.launch({headless:true, args:['--autoplay-policy=no-user-gesture-required']});
  try {
    const context = await browser.newContext({viewport:{width:1100,height:800}});
    const page = await context.newPage(), failures = [];
    page.on('pageerror', error => failures.push('pageerror: ' + error.message));
    page.on('console', message => { if (message.type() === 'error') failures.push('console: ' + message.text()); });
    await page.goto(url, {waitUntil:'domcontentloaded'});
    await page.locator('#example-title').waitFor();
    await page.waitForFunction(() => { const audio=document.querySelector('#source-audio'); return audio && audio.readyState >= 1 && Number.isFinite(audio.duration) && audio.duration > 0; }, undefined, {timeout:15000});
    assert(await page.locator('#source-audio').evaluate(audio => audio.controls && !!audio.currentSrc), 'Áudio nativo por URL não está disponível.');
    const total = await page.locator('input[name="perceived-change"]').count();
    assert.equal(total, 5, 'As cinco respostas opcionais não foram renderizadas.');
    assert.equal(await page.locator('input[name="perceived-change"]:checked').count(), 0, 'A resposta inicial deve ficar sem seleção.');
    assert(await page.locator('#counter').innerText().then(value => /Exemplo 1 de 4/.test(value)), 'O conjunto esperado deve conter quatro exemplos.');
    await page.locator('#source-audio').evaluate(audio => { audio.muted=true; });
    await page.locator('#listen-clip').click();
    await page.waitForFunction(() => !document.querySelector('#source-audio').paused, undefined, {timeout:5000});
    await page.evaluate(() => window.__songvizListeningExamples.playRange(.05,.12));
    await page.waitForFunction(() => { const audio=document.querySelector('#source-audio'); return audio.paused && audio.currentTime <= .13; }, undefined, {timeout:5000});
    assert.equal(await page.evaluate(() => window.__songvizListeningExamples.playRange(2,2)), false, 'Intervalo inválido não deve iniciar reprodução.');
    await page.locator('input[value="local"]').check();
    await page.locator('#clear-choice').click();
    assert.equal(await page.locator('input[name="perceived-change"]:checked').count(), 0, 'Limpar escolha deve restaurar a resposta null.');
    await page.locator('input[value="local"]').check();
    await page.locator('#notes').fill('A nota opcional continua ao navegar.');
    await page.locator('details').first().click();
    assert.equal(await page.locator('details').first().evaluate(detail => detail.open), true, 'A explicação deveria abrir apenas quando solicitada.');
    await page.locator('#next').click();
    assert(await page.locator('#counter').innerText().then(value => /Exemplo 2 de 4/.test(value)), 'Próximo não navegou sem exigir uma resposta.');
    assert.equal(await page.locator('details').first().evaluate(detail => detail.open), false, 'A explicação anterior deve fechar ao navegar.');
    await page.locator('#previous').click();
    assert.equal(await page.locator('input[value="local"]').isChecked(), true, 'A resposta não foi preservada ao voltar.');
    assert.equal(await page.locator('#notes').inputValue(), 'A nota opcional continua ao navegar.', 'A nota não foi preservada ao voltar.');
    const download = page.waitForEvent('download');
    await page.locator('#export-feedback').click();
    const stream = await (await download).createReadStream();
    let exported = ''; for await (const chunk of stream) exported += chunk;
    const payload = JSON.parse(exported);
    assert.equal(payload.schema_version, 1, 'Versão do JSON exportado incorreta.');
    assert.equal(payload.kind, 'songviz-listening-examples-feedback', 'Tipo do JSON exportado incorreto.');
    assert.equal(payload.answers.length, 4, 'Exportação deve incluir todos os quatro exemplos.');
    assert.equal(payload.answers[0].perceived_change, 'local', 'Resposta escolhida ausente da exportação.');
    assert(payload.answers.slice(1).every(answer => answer.perceived_change === null), 'Respostas desconhecidas devem permanecer null.');
    await page.reload({waitUntil:'domcontentloaded'});
    await page.locator('input[value="local"]').waitFor();
    assert.equal(await page.locator('input[value="local"]').isChecked(), true, 'Rascunho não persistiu no mesmo contexto.');
    await page.setViewportSize({width:375,height:812});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'Há overflow horizontal no celular.');
    const isolated = await browser.newContext({viewport:{width:375,height:812}}), fresh = await isolated.newPage();
    const isolatedFailures = [];
    fresh.on('pageerror', error => isolatedFailures.push(error.message));
    await fresh.goto(url, {waitUntil:'domcontentloaded'});
    await fresh.locator('input[name="perceived-change"]').first().waitFor();
    assert.equal(await fresh.locator('input[name="perceived-change"]:checked').count(), 0, 'Um contexto isolado não deve herdar o rascunho.');
    await fresh.locator('#next').click();
    assert(await fresh.locator('#counter').innerText().then(value => /Exemplo 2 de 4/.test(value)), 'Navegação sem resposta falhou no contexto isolado.');
    assert.deepEqual(isolatedFailures, [], isolatedFailures.join('\n'));
    await isolated.close();
    assert.deepEqual(failures, [], failures.join('\n'));
    console.log('PASS: áudio nativo, trecho limitado, respostas opcionais, exportação, rascunho isolado/persistente, navegação, celular e sem erros.');
    await context.close();
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
